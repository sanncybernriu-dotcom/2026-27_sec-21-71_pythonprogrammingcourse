# Python Comparision Operators Exercise
a=10
b=5
result = a > b # Greater than comparision
print("result of",a, ">",b,"is : ",result)

result = a < b # Less than comaparision
print("result of",a,"<",b,"is :",result)

result = a>=b # GREATER THAN EQUAL TO COMPARISION
print("result of",a,">=",b,"is :",result)

result = a<=b # LESSER THAN EQUAL TO COMPARISION
print("result of",a,"<=",b,"is :",result)

result = a!=b  # NOT EQUAL COMPARISION
print("result of",a,"!=",b,"is :",result)
 
result = a==b
print("result of",a,"==",b,"is :",result)